"use strict";
const fs=require("fs");
const path=require("path");
const HERE=__dirname;
const ROOT=path.resolve(HERE,"..");
const versionPath=path.join(HERE,"version.json");
const latestPath=path.join(ROOT,"latest.json");
const propsPath=path.join(HERE,"version.properties");
const version=JSON.parse(fs.readFileSync(versionPath,"utf8"));
version.versionCode=Number(version.versionCode||1)+1;
const parts=String(version.versionName||"1.0.0").split(".").map(Number);
while(parts.length<3) parts.push(0);
parts[2]=Number(parts[2]||0)+1;
version.versionName=parts.slice(0,3).join(".");
version.releasedAt=new Date().toISOString().slice(0,10);
fs.writeFileSync(versionPath,JSON.stringify(version,null,2)+"\n","utf8");
fs.writeFileSync(latestPath,JSON.stringify(version,null,2)+"\n","utf8");
fs.writeFileSync(propsPath,`versionCode=${version.versionCode}\nversionName=${version.versionName}\n`,"ascii");
console.log(`version ${version.versionCode} / ${version.versionName}`);
